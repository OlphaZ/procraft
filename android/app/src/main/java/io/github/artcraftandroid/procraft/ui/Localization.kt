    private val foldedTranslations by lazy { translations.mapKeys { it.key.lowercase(java.util.Locale.ROOT) } }

    private fun translateDynamic(text: String): String {
        for ((pattern, replacement) in dynamicTranslations) {
            val match = pattern.matchEntire(text) ?: continue
            return Regex("[{]([0-9]+)[}]").replace(replacement) { placeholder ->
                match.groupValues.getOrElse(placeholder.groupValues[1].toInt()) { placeholder.value }
            }
        }
        return text
    }

    private val dynamicTranslations = listOf(
        Regex("^([0-9]+) saved to Gallery$") to "已将 {1} 个文件保存到图库",
        Regex("^Saved ([0-9]+) of ([0-9]+) to Gallery$") to "已将 {2} 个文件中的 {1} 个保存到图库",
        Regex("^Delete ([0-9]+) artworks[?]$") to "删除 {1} 件作品？",
        Regex("^Undo (.+)$") to "撤销：{1}",
        Regex("^Redo (.+)$") to "重做：{1}",
        Regex("^Frame ([0-9]+)$") to "第 {1} 帧",
        Regex("^([0-9]+) artworks$") to "{1} 件作品",
        Regex("^Selection Threshold (.+)$") to "选区阈值 {1}",
        Regex("^Threshold (.+)$") to "阈值 {1}",
        Regex("^Last reset point: (.+)$") to "上次重置点：{1}",
        Regex("^Made by (.+)$") to "作者：{1}",
    )
