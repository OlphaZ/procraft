object UiLanguage {
    var chinese by mutableStateOf(false)
        private set

    fun load(context: Context) {
        val language = context.getSharedPreferences("interface", Context.MODE_PRIVATE)
            .getString("language", "system")
        chinese = if (language == "system") ConfigurationCompat.getLocales(context.resources.configuration)[0]?.language == "zh" else language == "zh-CN"
    }

    fun set(context: Context, language: String) {
        context.getSharedPreferences("interface", Context.MODE_PRIVATE).edit()
            .putString("language", language).apply()
        chinese = if (language == "system") ConfigurationCompat.getLocales(context.resources.configuration)[0]?.language == "zh" else language == "zh-CN"
    }

    fun translate(text: String): String = translate(text, chinese)

    internal fun translate(text: String, useChinese: Boolean): String {
        if (!useChinese) return text
        translations[text]?.let { return it }
        val trimmed = text.trim()
        translations[trimmed]?.let { return text.replace(trimmed, it) }
        foldedTranslations[trimmed.lowercase(java.util.Locale.ROOT)]?.let { return text.replace(trimmed, it) }
        return translateDynamic(text)
    }

